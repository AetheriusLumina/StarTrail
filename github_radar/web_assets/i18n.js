function t(value, values = {}) {
  const template = typeof language !== "undefined" && language === "en"
    ? (RADAR_EN[value] || value) : value;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match);
}

function tr(value) {
  return t(value);
}

function localizeServerText(value) {
  if (language !== "en" || typeof value !== "string") return value;
  if (RADAR_EN[value]) return RADAR_EN[value];
  const patterns = [
    [/^关键词：(.+)$/, (_, term) => `Keyword: ${term}`],
    [/^新增 ([\d,]+) Star$/, (_, count) => `+${count} new Stars`],
    [/^GitHub 统计日：(.+)$/, (_, day) => `GitHub statistical date: ${day}`],
    [/^观察区间：(.+)$/, (_, interval) => `Observation period: ${interval}`],
    [/^关键词「(.+)」符合条件的新项目不足 5 个$/, (_, term) => `Fewer than five qualifying new projects for “${term}”`],
    [/^同一统计日仅核实 (\d+) 个新项目，保留旧榜，补齐待重试$/, (_, count) => `Only ${count} new projects could be verified for the same day. The saved issue is kept; retry later.`],
    [/^更新失败：(.+)$/, (_, reason) => `Update failed: ${localizeServerText(reason)}`],
    [/^请求失败（(\d+)）$/, (_, status) => `Request failed (${status})`],
  ];
  for (const [pattern, format] of patterns) {
    const match = pattern.exec(value);
    if (match) return value.replace(pattern, format);
  }
  return value;
}
